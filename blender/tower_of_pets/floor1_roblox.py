"""TOWER OF PETS - Floor 1 Roblox delivery for the environment detail pass.

write_scatter()  -> exports/TowerOfPets/Floor1/Scatter/Floor1_Scatter_<Category>_<n>.lua (placement data ModuleScripts)
                    + Floor1_Scatter.lua (the placer) + Floor1_Lighting.lua
export_assets()  -> exports/TowerOfPets/Floor1/Floor1_Assets.fbx + Floor1_Palette.png: every scattered asset once, as a
                    single MeshPart coloured by a small palette texture (one draw-call-friendly mesh per asset instead
                    of one MeshPart per material), all at the origin.
Placement data is in Roblox coordinates: (x, y, z) Blender -> (x, z, -y); rotation about Blender Z = about Roblox Y.
"""
import os, math, json, struct, zlib

# collision / streaming rules per category (also documented in IMPORT.md)
RULES = {
    'Trees':      'collide = false, trunk = true, shadow = true',
    'Foliage':    'collide = false, shadow = false',
    'Rocks':      'collide = true, fidelity = "Hull", shadow = true, smallNoCollide = 4',
    'Props':      'collide = true, fidelity = "Box", shadow = true',
    'Ruins':      'collide = true, fidelity = "Hull", shadow = true',
    'Water':      'collide = false, shadow = false',
    'Cliffs':     'collide = false, shadow = false',
    'Landmarks':  'collide = false, shadow = true, persistent = true',
    'Background': 'collide = false, shadow = false, persistent = true',
}
TRUNKS = {  # asset -> (trunk radius, collider height) at scale 1, studs
    'Tree_Large_Low': (2.3, 9), 'Tree_Medium_Low': (1.4, 8), 'Tree_Small_Low': (1.2, 6), 'Tree_Tall_Thin_Low': (1.0, 10),
    'Tree_Large_Mystic': (2.3, 9), 'Tree_Medium_Mystic': (1.4, 8), 'Tree_Small_Mystic': (1.2, 6),
    'Tree_Tall_Thin_Mystic': (1.0, 10),
}
TRANSPARENT = {'Mist_Puff': 0.45}
LIGHTS = {'Lantern_Wood': (7.4, 22, 1.4)}      # asset -> (light height at scale 1, range, brightness)


def to_roblox(x, y, z):
    return x, z, -y


# ---------------------------------------------------------------- scatter data + scripts
def write_scatter(placed, offsets, out_dir, max_chars=150_000):
    sdir = os.path.join(out_dir, 'Scatter')
    os.makedirs(sdir, exist_ok=True)
    for f in os.listdir(sdir):
        if f.startswith('Floor1_Scatter_') and f.endswith('.lua'):
            os.remove(os.path.join(sdir, f))
    by_cat = {}
    for cat, asset, x, y, z, rot, s in placed:
        rx, ry, rz = to_roblox(x, y, z)
        by_cat.setdefault(cat, {}).setdefault(asset, []).append(
            f'{rx:.0f},{ry:.1f},{rz:.0f},{math.degrees(rot) % 360:.0f},{s:.2f}')
    files = []
    for cat in sorted(by_cat):
        chunks, cur, size = [], {}, 0
        for asset in sorted(by_cat[cat]):
            for item in by_cat[cat][asset]:
                if size > max_chars:
                    chunks.append(cur); cur, size = {}, 0
                cur.setdefault(asset, []).append(item)
                size += len(item) + 1
        if cur:
            chunks.append(cur)
        for k, ch in enumerate(chunks):
            name = f'Floor1_Scatter_{cat}_{k + 1}'
            L = [f'-- Tower of Pets Floor 1 scatter: {cat} ({sum(len(v) for v in ch.values())} placements).',
                 '-- Generated by blender/tower_of_pets/build_floor1_pack.py - x, y, z (studs), yaw (deg), scale.',
                 'return {', f'\tcategory = "{cat}",', '\titems = {']
            for asset in sorted(ch):
                L.append(f'\t\t{asset} = {{{",".join(ch[asset])}}},')
            L += ['\t},', '}', '']
            with open(os.path.join(sdir, name + '.lua'), 'w') as f:
                f.write('\n'.join(L))
            files.append(name)
    write_placer(out_dir, offsets)
    write_lighting(out_dir)
    return files, {c: sum(len(v) for v in by_cat[c].values()) for c in by_cat}


def write_placer(out_dir, offsets):
    L = ['-- Tower of Pets Floor 1: places the environment detail (trees, foliage, rocks, props, ruins, water and',
         '-- cliff dressing, landmark pieces, background) from the Floor1_Scatter_* data modules.',
         '-- Generated by blender/tower_of_pets/build_floor1_pack.py. See exports/TowerOfPets/Floor1/IMPORT.md.',
         '--',
         '-- Setup: import Floor1_Assets.fbx and put the imported model in ServerStorage named "Floor1_Assets";',
         '-- put every Floor1_Scatter_* ModuleScript in a Folder ServerStorage.Floor1_ScatterData; then run in the',
         '-- command bar:  require(game.ServerStorage.Floor1_Scatter).place()',
         '-- Options: place({texture = "rbxassetid://<palette id>", lights = true, categories = {"Trees", ...}})',
         '-- Categories: Trees, Foliage, Rocks, Props, Ruins, Water, Cliffs, Landmarks, Background',
         'local M = {}', '',
         '-- collision / shadows / streaming per category',
         'M.Rules = {']
    for cat, r in RULES.items():
        L.append(f'\t{cat} = {{{r}}},')
    L += ['}', '',
          '-- asset -> offset (studs, Roblox axes) from the asset\'s ground origin to its mesh centre, at scale 1',
          'M.Offsets = {']
    for name in sorted(offsets):
        ox, oy, oz = offsets[name]
        L.append(f'\t{name} = Vector3.new({ox:.3f}, {oy:.3f}, {oz:.3f}),')
    L += ['}', '', '-- tree trunks get a simple invisible cylinder collider: radius, height (scale 1)', 'M.Trunks = {']
    for name, (r, h) in TRUNKS.items():
        L.append(f'\t{name} = {{{r}, {h}}},')
    L += ['}', '', 'M.Transparency = {' + ', '.join(f'{k} = {v}' for k, v in TRANSPARENT.items()) + '}',
          'M.Lights = {' + ', '.join(f'{k} = {{{h}, {r}, {b}}}' for k, (h, r, b) in LIGHTS.items()) + '}', '',
          'local function findAsset(assets, name)',
          '\tlocal a = assets:FindFirstChild(name, true)',
          '\tif a and a:IsA("Model") then a = a:FindFirstChildWhichIsA("MeshPart", true) end',
          '\treturn a',
          'end', '',
          'function M.place(opts)',
          '\topts = opts or {}',
          '\tlocal assets = opts.assets or game.ServerStorage:FindFirstChild("Floor1_Assets")',
          '\tlocal data = opts.data or game.ServerStorage:FindFirstChild("Floor1_ScatterData")',
          '\tassert(assets, "put the imported Floor1_Assets model in ServerStorage")',
          '\tassert(data, "put the Floor1_Scatter_* modules in ServerStorage.Floor1_ScatterData")',
          '\tlocal only = nil',
          '\tif opts.categories then only = {}; for _, c in ipairs(opts.categories) do only[c] = true end end',
          '\t-- no categories: rebuild everything; with categories: replace only those (run one category at a time',
          '\t-- if a single big call is too slow)',
          '\tlocal root = (opts.parent or workspace):FindFirstChild("Floor1_Environment")',
          '\tif root and not only then root:Destroy(); root = nil end',
          '\tif not root then',
          '\t\troot = Instance.new("Folder"); root.Name = "Floor1_Environment"; root.Parent = opts.parent or workspace',
          '\tend',
          '\tif only then for c in pairs(only) do local old = root:FindFirstChild(c); if old then old:Destroy() end end end',
          '\tlocal groups, count, missing = {}, 0, {}',
          '\tfor _, mod in ipairs(data:GetChildren()) do',
          '\t\tif not mod:IsA("ModuleScript") then continue end',
          '\t\tlocal d = require(mod)',
          '\t\tif only and not only[d.category] then continue end',
          '\t\tlocal rule = M.Rules[d.category] or {}',
          '\t\tlocal g = groups[d.category]',
          '\t\tif not g then',
          '\t\t\tg = Instance.new("Model"); g.Name = d.category',
          '\t\t\tif rule.persistent then g.ModelStreamingMode = Enum.ModelStreamingMode.Persistent end',
          '\t\t\tg.Parent = root; groups[d.category] = g',
          '\t\tend',
          '\t\tfor name, arr in pairs(d.items) do',
          '\t\t\tlocal src = findAsset(assets, name)',
          '\t\t\tif not src then missing[name] = true; continue end',
          '\t\t\tlocal off = M.Offsets[name] or Vector3.zero',
          '\t\t\tlocal trunk, light = M.Trunks[name], M.Lights[name]',
          '\t\t\tfor i = 1, #arr, 5 do',
          '\t\t\t\tlocal s = arr[i + 4]',
          '\t\t\t\tlocal base = CFrame.new(arr[i], arr[i + 1], arr[i + 2]) * CFrame.Angles(0, math.rad(arr[i + 3]), 0)',
          '\t\t\t\tlocal p = src:Clone()',
          '\t\t\t\tp.Name = name',
          '\t\t\t\tp.Size = src.Size * s',
          '\t\t\t\tp.CFrame = base * CFrame.new(off * s)',
          '\t\t\t\tp.Anchored = true',
          '\t\t\t\tif opts.texture then p.TextureID = opts.texture end',
          '\t\t\t\tp.Transparency = M.Transparency[name] or 0',
          '\t\t\t\tlocal small = rule.smallNoCollide and p.Size.Magnitude < rule.smallNoCollide * 3',
          '\t\t\t\tp.CanCollide = rule.collide == true and not small',
          '\t\t\t\tp.CanQuery, p.CanTouch = p.CanCollide, false',
          '\t\t\t\tp.CastShadow = rule.shadow == true',
          '\t\t\t\tif p.CanCollide and rule.fidelity then',
          '\t\t\t\t\tpcall(function() p.CollisionFidelity = Enum.CollisionFidelity[rule.fidelity] end)',
          '\t\t\t\telse',
          '\t\t\t\t\tpcall(function() p.CollisionFidelity = Enum.CollisionFidelity.Box end)',
          '\t\t\t\tend',
          '\t\t\t\tp.Parent = g',
          '\t\t\t\tif rule.trunk and trunk then  -- riders bump into trunks, ride under canopies',
          '\t\t\t\t\tlocal c = Instance.new("Part")',
          '\t\t\t\t\tc.Name = name .. "_Trunk"',
          '\t\t\t\t\tc.Shape = Enum.PartType.Cylinder',
          '\t\t\t\t\tc.Size = Vector3.new(trunk[2] * s, trunk[1] * 2 * s, trunk[1] * 2 * s)',
          '\t\t\t\t\tc.CFrame = base * CFrame.new(0, trunk[2] * s / 2, 0) * CFrame.Angles(0, 0, math.rad(90))',
          '\t\t\t\t\tc.Anchored, c.Transparency, c.CastShadow, c.CanTouch = true, 1, false, false',
          '\t\t\t\t\tc.Parent = p',
          '\t\t\t\tend',
          '\t\t\t\tif opts.lights and light then',
          '\t\t\t\t\tlocal a = Instance.new("Attachment"); a.Position = p.CFrame:PointToObjectSpace(',
          '\t\t\t\t\t\t(base * CFrame.new(0, light[1] * s, 0)).Position); a.Parent = p',
          '\t\t\t\t\tlocal l = Instance.new("PointLight"); l.Range = light[2]; l.Brightness = light[3]',
          '\t\t\t\t\tl.Color = Color3.fromRGB(255, 196, 120); l.Shadows = false; l.Parent = a',
          '\t\t\t\tend',
          '\t\t\t\tcount += 1',
          '\t\t\tend',
          '\t\tend',
          '\tend',
          '\tfor name in pairs(missing) do warn("Floor1_Scatter: asset not found: " .. name) end',
          '\tprint(("Floor1_Scatter: placed %d pieces"):format(count))',
          '\treturn root',
          'end', '',
          '-- palette texture for every asset (if the importer did not bring it in): upload Floor1_Palette.png, then',
          '-- require(game.ServerStorage.Floor1_Scatter).setTexture("rbxassetid://<id>")',
          'function M.setTexture(id, where)',
          '\tfor _, p in ipairs((where or workspace:FindFirstChild("Floor1_Environment")):GetDescendants()) do',
          '\t\tif p:IsA("MeshPart") then p.TextureID = id end',
          '\tend',
          'end', '', 'return M', '']
    with open(os.path.join(out_dir, 'Floor1_Scatter.lua'), 'w') as f:
        f.write('\n'.join(L))


