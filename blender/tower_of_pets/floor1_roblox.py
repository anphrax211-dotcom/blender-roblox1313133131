# ---------------------------------------------------------------- asset library export (palette textured)
def png_write(path, w, h, rgb_rows):
    raw = b''.join(b'\x00' + bytes(row) for row in rgb_rows)
    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0))
                + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def export_assets(blend, out_dir):
    """every asset used by the scatter, once, as one palette-textured MeshPart at the origin"""
    import bpy, bmesh
    import export_fbx
    bpy.ops.wm.open_mainfile(filepath=blend)
    used = sorted({o.data.name for o in bpy.data.collections['SCATTER'].all_objects if o.type == 'MESH'})
    srcs = {n[len('ASSET_'):]: bpy.data.meshes[n] for n in used if n.startswith('ASSET_')}
    mats = sorted({m.name for me in srcs.values() for m in me.materials if m})
    N = 1
    while N * N < len(mats):
        N *= 2
    cell = 8
    cols = {}
    for k, name in enumerate(mats):
        c = export_fbx.rep_color(bpy.data.materials[name])
        cols[name] = (k // N, k % N, tuple(int(round(export_fbx.lin2srgb(v) * 255)) for v in c))
    rows = []
    for r in range(N * cell):
        row = []
        for cc in range(N * cell):
            k = (r // cell) * N + cc // cell
            rgb = cols[mats[k]][2] if k < len(mats) else (255, 0, 255)
            row += list(rgb)
        rows.append(row)
    png = os.path.join(out_dir, 'Floor1_Palette.png')
    png_write(png, N * cell, N * cell, rows)
    img = bpy.data.images.load(png)
    pal = bpy.data.materials.new('F1_Palette')
    pal.use_nodes = True
    nt = pal.node_tree
    tex = nt.nodes.new('ShaderNodeTexImage'); tex.image = img; tex.interpolation = 'Closest'
    nt.links.new(tex.outputs['Color'], nt.nodes['Principled BSDF'].inputs['Base Color'])
    scene_coll = bpy.data.collections.new('_ASSET_EXPORT')
    bpy.context.scene.collection.children.link(scene_coll)
    objs, offsets, tris = [], {}, 0
    for name, src in sorted(srcs.items()):
        bm = bmesh.new(); bm.from_mesh(src)
        bmesh.ops.triangulate(bm, faces=bm.faces[:])
        uv = bm.loops.layers.uv.new('Palette')
        for f in bm.faces:
            m = src.materials[f.material_index] if f.material_index < len(src.materials) else None
            r, c, _ = cols.get(m.name if m else mats[0], cols[mats[0]])
            u, v = (c + 0.5) / N, 1 - (r + 0.5) / N
            for lp in f.loops:
                lp[uv].uv = (u, v)
            f.material_index = 0
        me = bpy.data.meshes.new(name)
        bm.to_mesh(me); bm.free()
        me.materials.append(pal)
        ob = bpy.data.objects.new(name, me)
        scene_coll.objects.link(ob)
        objs.append(ob)
        xs = [v.co for v in me.vertices]
        ctr = [(max(c[a] for c in xs) + min(c[a] for c in xs)) / 2 for a in range(3)]
        offsets[name] = to_roblox(*ctr)
        tris += len(me.polygons)
    for o in bpy.context.view_layer.objects:
        o.select_set(False)
    for o in objs:
        o.select_set(True)
    path = os.path.join(out_dir, 'Floor1_Assets.fbx')
    bpy.ops.export_scene.fbx(filepath=path, use_selection=True, object_types={'MESH'}, apply_unit_scale=True,
                             apply_scale_options='FBX_SCALE_NONE', global_scale=1.0, axis_forward='-Z', axis_up='Y',
                             mesh_smooth_type='FACE', use_mesh_modifiers=False, add_leaf_bones=False, bake_anim=False,
                             path_mode='COPY', embed_textures=True, use_custom_props=False)
    print(f'Floor1_Assets: {len(objs)} assets, {tris:,} tris, palette {N}x{N} ({len(mats)} colours), '
          f'{os.path.getsize(path) / 1e6:.2f} MB')
    return offsets, dict(assets=len(objs), triangles=tris, palette_colours=len(mats))


# ---------------------------------------------------------------- one-click script bundle for Studio
def write_rbxmx(out_dir):
    """Floor1_Scripts.rbxmx: Floor1_Materials, Floor1_Scatter, Floor1_Lighting and the Floor1_ScatterData folder as
    ModuleScripts - in Studio: right-click ServerStorage > Insert from File... > this file"""
    from xml.sax.saxutils import escape
    ref = [0]

    def item(cls, name, source=None, children=()):
        ref[0] += 1
        props = f'<string name="Name">{escape(name)}</string>'
        if source is not None:
            assert ']]>' not in source
            props += f'<ProtectedString name="Source"><![CDATA[{source}]]></ProtectedString>'
        return (f'<Item class="{cls}" referent="RBX{ref[0]}"><Properties>{props}</Properties>'
                + ''.join(children) + '</Item>')

    def read(p):
        with open(p) as f:
            return f.read()
    items = [item('ModuleScript', n, read(os.path.join(out_dir, n + '.lua')))
             for n in ('Floor1_Materials', 'Floor1_Scatter', 'Floor1_Lighting')]
    sdir = os.path.join(out_dir, 'Scatter')
    mods = [item('ModuleScript', f[:-4], read(os.path.join(sdir, f))) for f in sorted(os.listdir(sdir)) if f.endswith('.lua')]
    items.append(item('Folder', 'Floor1_ScatterData', children=mods))
    xml = ('<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" '
           'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
           'xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4">'
           + ''.join(items) + '</roblox>')
    path = os.path.join(out_dir, 'Floor1_Scripts.rbxmx')
    with open(path, 'w') as f:
        f.write(xml)
    print(f'Floor1_Scripts.rbxmx: {len(items) - 1} modules + {len(mods)} scatter data modules, '
          f'{os.path.getsize(path) / 1e6:.2f} MB')
    return path
